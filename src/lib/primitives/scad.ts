import type { PrimitiveConfig } from "./types";
import { footprintRadius, resolveChamfer, resolveFit, resolveGroove, resolveKnurl } from "./geometry";

/**
 * Renders a primitive as self-contained pure OpenSCAD (no libraries). The
 * chamfer is a 45° bevel on both ends; knurling is a union of side ribs
 * trimmed back by the chamfered outer body, matching the STL preview.
 *
 * With the lid fit enabled the part becomes a stepped lid: a smaller spigot at
 * the base, bevelled at its bottom edge, topped by the full-size flange whose
 * top edge carries the second bevel.
 */
export function generatePrimitiveScad(config: PrimitiveConfig): string {
  const num = (v: number) => String(Math.round(v * 1000) / 1000);
  const chamfer = resolveChamfer(config);
  const knurl = resolveKnurl(config);
  const fit = resolveFit(config);
  const height = Math.max(0.5, config.height);
  const fitHeight = fit ? Math.min(fit.height, Math.max(0.5, height - 0.5)) : 0;
  const flangeHeight = height - fitHeight;
  const r = footprintRadius(config);
  const groove = resolveGroove(config);
  const grooveOnSpigot = groove !== null && fit !== null && groove.bottom + groove.width <= fitHeight + 1e-9;
  const grooveRadius = groove
    ? Math.max(0.1, (grooveOnSpigot ? r - (fit?.clearance ?? 0) : r) - groove.depth)
    : 0;
  const lines: string[] = [];

  lines.push("// Generated by 3dlabOpen Primitive Generator");
  lines.push("// Pure OpenSCAD - no external libraries required");
  lines.push("$fn = 96;");
  lines.push("");

  lines.push("// --- Parameters ---");
  lines.push(`H = ${num(height)};`);
  lines.push(`C = ${num(chamfer)};`);
  if (config.shape === "cylinder") {
    lines.push(`R = ${num(r)};`);
  } else {
    lines.push(`W = ${num(config.width)};`);
    lines.push(`D = ${num(config.depth)};`);
  }
  if (fit) {
    lines.push(`E = ${num(fitHeight)};`);
    lines.push(`HF = ${num(flangeHeight)};`);
    if (config.shape === "cylinder") {
      lines.push(`RF = ${num(Math.max(0.1, r - fit.clearance))};`);
    } else {
      lines.push(`WF = ${num(Math.max(0.2, config.width - 2 * fit.clearance))};`);
      lines.push(`DF = ${num(Math.max(0.2, config.depth - 2 * fit.clearance))};`);
    }
  }
  if (knurl.depth > 0) {
    lines.push(`RIDGES = ${knurl.ridges};`);
    lines.push(`DEPTH = ${num(knurl.depth)};`);
  }
  lines.push("");

  const topChamferModule = config.shape === "cylinder" ? "top_chamfer_cylinder(R, HF, C)" : "box_top_chamfer(W, D, HF, C)";

  if (config.shape === "cylinder") {
    lines.push(
      "module chamfered_cylinder(r, h, c) {",
      "    rotate_extrude($fn = 96)",
      "        polygon(points = [[0, 0], [r - c, 0], [r, c], [r, h - c], [r - c, h], [0, h]]);",
      "}",
      "",
      "module knurled_cylinder(r, h, ridges, depth) {",
      "    w = 2 * PI * r / ridges * 0.5;",
      "    union() {",
      "        cylinder(h = h, r = r - depth, $fn = 96);",
      "        for (i = [0 : ridges - 1]) {",
      "            rotate([0, 0, i * 360 / ridges])",
      "                translate([r - depth, -w / 2, 0])",
      "                    cube([depth * 1.4, w, h]);",
      "        }",
      "    }",
      "}",
      ""
    );

    if (fit) {
      lines.push(
        "module top_chamfer_cylinder(r, h, c) {",
        "    rotate_extrude($fn = 96)",
        "        polygon(points = [[0, 0], [r, 0], [r, h - c], [r - c, h], [0, h]]);",
        "}",
        "",
        "module bottom_chamfer_cylinder(r, h, c) {",
        "    rotate_extrude($fn = 96)",
        "        polygon(points = [[0, 0], [r - c, 0], [r, c], [r, h], [0, h]]);",
        "}",
        ""
      );

      lines.push("module spigot() {");
      lines.push(chamfer > 0 ? "    bottom_chamfer_cylinder(RF, E, C);" : "    cylinder(h = E, r = RF);");
      lines.push("}", "");

      lines.push("module flange() {");
      if (knurl.depth > 0) {
        lines.push(
          "    intersection() {",
          "        knurled_cylinder(R, HF, RIDGES, DEPTH);",
          chamfer > 0 ? `        ${topChamferModule};` : "        cylinder(h = HF, r = R);",
          "    }"
        );
      } else {
        lines.push(chamfer > 0 ? `    ${topChamferModule};` : "    cylinder(h = HF, r = R);");
      }
      lines.push("}", "");

      lines.push(
        "module body() {",
        "    union() {",
        "        spigot();",
        "        translate([0, 0, E]) flange();",
        "    }",
        "}",
        ""
      );
    } else {
      const bodyShape = knurl.depth > 0 ? "knurled_cylinder(R, H, RIDGES, DEPTH)" : "cylinder(h = H, r = R)";
      lines.push("module body() {");
      if (chamfer > 0) {
        lines.push("    intersection() {", `        ${bodyShape};`, "        chamfered_cylinder(R, H, C);", "    }");
      } else {
        lines.push(`    ${bodyShape};`);
      }
      lines.push("}", "");
    }

    if (groove) {
      lines.push(
        "module primitive() {",
        "    difference() {",
        "        union() {",
        "            body();",
        "            // Smooth channel floor, so the knurl never dips into the groove.",
        `            translate([0, 0, ${num(groove.bottom)}])`,
        `                cylinder(h = ${num(groove.width)}, r = ${num(grooveRadius)}, $fn = 96);`,
        "        }",
        `        translate([0, 0, ${num(groove.bottom)}])`,
        "            difference() {",
        `                cylinder(h = ${num(groove.width)}, r = R + 1, $fn = 96);`,
        `                translate([0, 0, -0.5]) cylinder(h = ${num(groove.width + 1)}, r = ${num(grooveRadius)}, $fn = 96);`,
        "            }",
        "    }",
        "}",
        ""
      );
    } else {
      lines.push("module primitive() {", "    body();", "}", "");
    }
    lines.push("primitive();");
  } else {
    lines.push(
      "// 45 deg bevel on the top and bottom edges only: the hull of the end faces",
      "// and the inset rings leaves the side faces planar and the corners mitered,",
      "// exactly like the mesh.",
      "module chamfered_box(w, d, h, c) {",
      "    if (c > 0) {",
      "        hull() {",
      "            translate([0, 0, 0.001]) cube([w, d, 0.002], center = true);",
      "            translate([0, 0, h - 0.001]) cube([w, d, 0.002], center = true);",
      "            translate([0, 0, c]) cube([max(w - 2 * c, 0.1), max(d - 2 * c, 0.1), 0.002], center = true);",
      "            translate([0, 0, h - c]) cube([max(w - 2 * c, 0.1), max(d - 2 * c, 0.1), 0.002], center = true);",
      "        }",
      "    } else {",
      "        translate([-w / 2, -d / 2, 0]) cube([w, d, h]);",
      "    }",
      "}",
      ""
    );

    if (knurl.depth > 0) {
      lines.push(
        "module knurled_box(w, d, h, ridges, depth, c) {",
        "    rib = 0.5;",
        "    union() {",
        "        chamfered_box(w - 2 * depth, d - 2 * depth, h, max(c - depth, 0));",
        "        for (i = [0 : ridges - 1]) {",
        "            y = -d / 2 + (i + 0.5) * d / ridges;",
        "            x = -w / 2 + (i + 0.5) * w / ridges;",
        "            // +/- X faces",
        "            translate([w / 2 - depth, y - d / ridges * rib / 2, 0])",
        "                cube([depth * 1.4, d / ridges * rib, h]);",
        "            translate([-w / 2 - depth * 0.4, y - d / ridges * rib / 2, 0])",
        "                cube([depth * 1.4, d / ridges * rib, h]);",
        "            // +/- Y faces",
        "            translate([x - w / ridges * rib / 2, d / 2 - depth, 0])",
        "                cube([w / ridges * rib, depth * 1.4, h]);",
        "            translate([x - w / ridges * rib / 2, -d / 2 - depth * 0.4, 0])",
        "                cube([w / ridges * rib, depth * 1.4, h]);",
        "        }",
        "    }",
        "}",
        ""
      );
    }

    if (fit) {
      lines.push(
        "// Box with the bevel on the top edge only.",
        "module box_top_chamfer(w, d, h, c) {",
        "    if (c > 0) {",
        "        difference() {",
        "            translate([0, 0, -c]) chamfered_box(w, d, h + c, c);",
        "            translate([-w, -d, -c - 1]) cube([2 * w, 2 * d, c + 1]);",
        "        }",
        "    } else {",
        "        translate([-w / 2, -d / 2, 0]) cube([w, d, h]);",
        "    }",
        "}",
        "",
        "// Box with the bevel on the bottom edge only.",
        "module box_bottom_chamfer(w, d, h, c) {",
        "    if (c > 0) {",
        "        difference() {",
        "            chamfered_box(w, d, h + c, c);",
        "            translate([-w, -d, h]) cube([2 * w, 2 * d, c + 1]);",
        "        }",
        "    } else {",
        "        translate([-w / 2, -d / 2, 0]) cube([w, d, h]);",
        "    }",
        "}",
        ""
      );

      lines.push("module spigot() {", "    box_bottom_chamfer(WF, DF, E, C);", "}", "");

      lines.push("module flange() {");
      if (knurl.depth > 0) {
        lines.push(
          "    intersection() {",
          "        knurled_box(W, D, HF, RIDGES, DEPTH, C);",
          "        box_top_chamfer(W, D, HF, C);",
          "    }"
        );
      } else {
        lines.push("    box_top_chamfer(W, D, HF, C);");
      }
      lines.push("}", "");

      lines.push(
        "module primitive() {",
        "    union() {",
        "        spigot();",
        "        translate([0, 0, E]) flange();",
        "    }",
        "}",
        ""
      );
    } else if (knurl.depth > 0) {
      lines.push(
        "module primitive() {",
        "    intersection() {",
        "        knurled_box(W, D, H, RIDGES, DEPTH, C);",
        "        chamfered_box(W, D, H, C);",
        "    }",
        "}",
        ""
      );
    } else {
      lines.push("module primitive() {", "    chamfered_box(W, D, H, C);", "}", "");
    }
    lines.push("primitive();");
  }

  return lines.join("\n");
}
