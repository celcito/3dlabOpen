import type { FitConfig } from "./types";
import { resolveFitPair } from "./fit";
import { lidToPrimitive } from "./lid";
import { resolveChamfer, resolveFit } from "../primitives/geometry";

/**
 * Renders the lid + container pair as self-contained pure OpenSCAD. Both
 * modules use the same resolved numbers as the mesh, so the printed pair mates
 * exactly like the preview.
 */
export function generateFitScad(config: FitConfig): string {
  const num = (v: number) => String(Math.round(v * 1000) / 1000);
  const fit = resolveFitPair(config);
  const lid = lidToPrimitive(config);
  const lidFit = resolveFit(lid)!;
  const lidChamfer = resolveChamfer(lid);
  const skirt = lidFit.height;
  const plate = Math.max(0.8, lid.height - skirt);

  const lines: string[] = [];
  lines.push("// Generated by 3dlabOpen Fit Configurator");
  lines.push("// Pure OpenSCAD - no external libraries required");
  lines.push("$fn = 96;");
  lines.push("");
  lines.push('PART = "both"; // "lid" | "container" | "both"');
  lines.push("");
  lines.push("// --- Parameters ---");
  lines.push(`H = ${num(fit.height)};`);
  lines.push(`F = ${num(fit.floor)};`);
  lines.push(`C = ${num(fit.chamfer)};`);
  lines.push(`CL = ${num(lidChamfer)};`);
  lines.push(`SKIRT = ${num(skirt)};`);
  lines.push(`PLATE = ${num(plate)};`);
  if (fit.circular) {
    lines.push(`RO = ${num(fit.outerHalfW)};`);
    lines.push(`RI = ${num(fit.innerHalfW)};`);
    lines.push(`RS = ${num(fit.skirtHalfW)};`);
  } else {
    lines.push(`W = ${num(fit.outerHalfW * 2)};`);
    lines.push(`D = ${num(fit.outerHalfD * 2)};`);
    lines.push(`IW = ${num(fit.innerHalfW * 2)};`);
    lines.push(`ID = ${num(fit.innerHalfD * 2)};`);
    lines.push(`SW = ${num(fit.skirtHalfW * 2)};`);
    lines.push(`SD = ${num(fit.skirtHalfD * 2)};`);
  }
  lines.push("");

  if (fit.circular) {
    lines.push(
      "module chamfered_cylinder(r, h, c) {",
      "    rotate_extrude($fn = 96)",
      "        polygon(points = [[0, 0], [r - c, 0], [r, c], [r, h - c], [r - c, h], [0, h]]);",
      "}",
      "",
      "module bottom_chamfer_cylinder(r, h, c) {",
      "    rotate_extrude($fn = 96)",
      "        polygon(points = [[0, 0], [r - c, 0], [r, c], [r, h], [0, h]]);",
      "}",
      "",
      "module top_chamfer_cylinder(r, h, c) {",
      "    rotate_extrude($fn = 96)",
      "        polygon(points = [[0, 0], [r, 0], [r, h - c], [r - c, h], [0, h]]);",
      "}",
      "",
      "module container() {",
      "    difference() {",
      "        chamfered_cylinder(RO, H, C);",
      "        translate([0, 0, F])",
      "            cylinder(h = H - F + 1, r = RI);",
      "    }",
      "}",
      "",
      "module lid() {",
      "    union() {",
      "        bottom_chamfer_cylinder(RS, SKIRT, CL);",
      "        translate([0, 0, SKIRT])",
      "            top_chamfer_cylinder(RO, PLATE, CL);",
      "    }",
      "}"
    );
  } else {
    lines.push(
      "// 45 deg bevel on the end edges only: the hull of the end faces and the",
      "// inset rings leaves the side faces planar, exactly like the mesh.",
      "module chamfered_box(w, d, h, c) {",
      "    if (c > 0) {",
      "        hull() {",
      "            translate([0, 0, 0.001]) cube([w, d, 0.002], center = true);",
      "            translate([0, 0, h - 0.001]) cube([w, d, 0.002], center = true);",
      "            translate([0, 0, c]) cube([max(w - 2 * c, 0.1), max(d - 2 * c, 0.1), 0.002], center = true);",
      "            translate([0, 0, h - c]) cube([max(w - 2 * c, 0.1), max(d - 2 * c, 0.1), 0.002], center = true);",
      "        }",
      "    } else {",
      "        translate([-w / 2, -d / 2, 0]) cube([w, d, h]);",
      "    }",
      "}",
      "",
      "// Box with the bevel on the top edge only.",
      "module box_top_chamfer(w, d, h, c) {",
      "    if (c > 0) {",
      "        difference() {",
      "            translate([0, 0, -c]) chamfered_box(w, d, h + c, c);",
      "            translate([-w, -d, -c - 1]) cube([2 * w, 2 * d, c + 1]);",
      "        }",
      "    } else {",
      "        translate([-w / 2, -d / 2, 0]) cube([w, d, h]);",
      "    }",
      "}",
      "",
      "// Box with the bevel on the bottom edge only.",
      "module box_bottom_chamfer(w, d, h, c) {",
      "    if (c > 0) {",
      "        difference() {",
      "            chamfered_box(w, d, h + c, c);",
      "            translate([-w, -d, h]) cube([2 * w, 2 * d, c + 1]);",
      "        }",
      "    } else {",
      "        translate([-w / 2, -d / 2, 0]) cube([w, d, h]);",
      "    }",
      "}",
      "",
      "module container() {",
      "    difference() {",
      "        chamfered_box(W, D, H, C);",
      "        translate([-IW / 2, -ID / 2, F])",
      "            cube([IW, ID, H - F + 1]);",
      "    }",
      "}",
      "",
      "module lid() {",
      "    union() {",
      "        box_bottom_chamfer(SW, SD, SKIRT, CL);",
      "        translate([0, 0, SKIRT])",
      "            box_top_chamfer(W, D, PLATE, CL);",
      "    }",
      "}"
    );
  }

  lines.push("");
  lines.push("module assembly() {");
  lines.push("    container();");
  lines.push("    translate([0, 0, H + 10]) lid();");
  lines.push("}");
  lines.push("");
  lines.push('if (PART == "lid") lid();');
  lines.push('else if (PART == "container") container();');
  lines.push("else assembly();");

  return lines.join("\n");
}
