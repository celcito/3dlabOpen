import type { PrimitiveConfig } from "./types";
import { footprintRadius, resolveChamfer, resolveKnurl } from "./geometry";

/**
 * Renders a primitive as self-contained pure OpenSCAD (no libraries). The
 * chamfer is a 45° bevel on both ends; knurling is a union of side ribs
 * trimmed back by the chamfered outer body, matching the STL preview.
 */
export function generatePrimitiveScad(config: PrimitiveConfig): string {
  const num = (v: number) => String(Math.round(v * 1000) / 1000);
  const chamfer = resolveChamfer(config);
  const knurl = resolveKnurl(config);
  const lines: string[] = [];

  lines.push("// Generated by 3dlabOpen Primitive Generator");
  lines.push("// Pure OpenSCAD - no external libraries required");
  lines.push("$fn = 96;");
  lines.push("");

  const r = footprintRadius(config);
  const height = Math.max(0.5, config.height);

  lines.push("// --- Parameters ---");
  lines.push(`H = ${num(height)};`);
  lines.push(`C = ${num(chamfer)};`);
  if (config.shape === "cylinder") {
    lines.push(`R = ${num(r)};`);
  } else {
    lines.push(`W = ${num(config.width)};`);
    lines.push(`D = ${num(config.depth)};`);
  }
  if (knurl.depth > 0) {
    lines.push(`RIDGES = ${knurl.ridges};`);
    lines.push(`DEPTH = ${num(knurl.depth)};`);
  }
  lines.push("");

  if (config.shape === "cylinder") {
    lines.push(
      "module chamfered_cylinder(r, h, c) {",
      "    rotate_extrude($fn = 96)",
      "        polygon(points = [[0, 0], [r - c, 0], [r, c], [r, h - c], [r - c, h], [0, h]]);",
      "}",
      "",
      "module knurled_cylinder(r, h, ridges, depth) {",
      "    w = 2 * PI * r / ridges * 0.5;",
      "    union() {",
      "        cylinder(h = h, r = r - depth, $fn = 96);",
      "        for (i = [0 : ridges - 1]) {",
      "            rotate([0, 0, i * 360 / ridges])",
      "                translate([r - depth, -w / 2, 0])",
      "                    cube([depth * 1.4, w, h]);",
      "        }",
      "    }",
      "}",
      ""
    );

    const body = knurl.depth > 0 ? "knurled_cylinder(R, H, RIDGES, DEPTH)" : "cylinder(h = H, r = R)";
    lines.push("module primitive() {");
    if (chamfer > 0) {
      lines.push("    intersection() {", `        ${body};`, "        chamfered_cylinder(R, H, C);", "    }");
    } else {
      lines.push(knurl.depth > 0 ? `    ${body};` : "    cylinder(h = H, r = R);");
    }
    lines.push("}", "");
    lines.push("primitive();");
  } else {
    lines.push(
      "module octahedron(r) {",
      "    polyhedron(",
      "        points = [[r, 0, 0], [-r, 0, 0], [0, r, 0], [0, -r, 0], [0, 0, r], [0, 0, -r]],",
      "        faces = [[0, 2, 4], [2, 1, 4], [1, 3, 4], [3, 0, 4], [2, 0, 5], [1, 2, 5], [3, 1, 5], [0, 3, 5]]",
      "    );",
      "}",
      "",
      "module chamfered_box(w, d, h, c) {",
      "    if (c > 0) {",
      "        translate([0, 0, h / 2])",
      "            minkowski() {",
      "                cube([max(w - 2 * c, 0.1), max(d - 2 * c, 0.1), max(h - 2 * c, 0.1)], center = true);",
      "                octahedron(c);",
      "            }",
      "    } else {",
      "        translate([-w / 2, -d / 2, 0]) cube([w, d, h]);",
      "    }",
      "}",
      ""
    );

    if (knurl.depth > 0) {
      lines.push(
        "module knurled_box(w, d, h, ridges, depth, c) {",
        "    rib = 0.5;",
        "    union() {",
        "        chamfered_box(w - 2 * depth, d - 2 * depth, h, max(c - depth, 0));",
        "        for (i = [0 : ridges - 1]) {",
        "            y = -d / 2 + (i + 0.5) * d / ridges;",
        "            x = -w / 2 + (i + 0.5) * w / ridges;",
        "            // +/- X faces",
        "            translate([w / 2 - depth, y - d / ridges * rib / 2, 0])",
        "                cube([depth * 1.4, d / ridges * rib, h]);",
        "            translate([-w / 2 - depth * 0.4, y - d / ridges * rib / 2, 0])",
        "                cube([depth * 1.4, d / ridges * rib, h]);",
        "            // +/- Y faces",
        "            translate([x - w / ridges * rib / 2, d / 2 - depth, 0])",
        "                cube([w / ridges * rib, depth * 1.4, h]);",
        "            translate([x - w / ridges * rib / 2, -d / 2 - depth * 0.4, 0])",
        "                cube([w / ridges * rib, depth * 1.4, h]);",
        "        }",
        "    }",
        "}",
        ""
      );
      lines.push(
        "module primitive() {",
        "    intersection() {",
        "        knurled_box(W, D, H, RIDGES, DEPTH, C);",
        "        chamfered_box(W, D, H, C);",
        "    }",
        "}",
        ""
      );
    } else {
      lines.push("module primitive() {", "    chamfered_box(W, D, H, C);", "}", "");
    }
    lines.push("primitive();");
  }

  return lines.join("\n");
}
