import { zipSync, strToU8 } from "fflate";

export const CORE_PATH = "3D/3dmodel.model";

const CONTENT_TYPES = `<?xml version="1.0" encoding="UTF-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
 <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
 <Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>
 <Default Extension="png" ContentType="image/png"/>
 <Default Extension="gcode" ContentType="text/plain"/>
 <Override PartName="/Metadata/SliceInfo.config" ContentType="application/vnd.bambulabs.sliceinfo"/>
</Types>`;

const RELS = `<?xml version="1.0" encoding="UTF-8"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
 <Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/>
</Relationships>`;

export interface CubeFixture {
  unit?: string;
  size?: [number, number, number];
  flip?: boolean;
  dropTop?: boolean;
  degenerate?: boolean;
  duplicate?: boolean;
  transform?: string;
}

/** Cubo 12 triângulos com winding externo correto (reversível nos testes). */
const CUBE_FACES: [number, number, number][] = [
  [0, 2, 1], [0, 3, 2], // bottom (-Z)
  [4, 5, 6], [4, 6, 7], // top (+Z)
  [0, 1, 5], [0, 5, 4], // front (-Y)
  [1, 2, 6], [1, 6, 5], // right (+X)
  [2, 3, 7], [2, 7, 6], // back (+Y)
  [3, 0, 4], [3, 4, 7], // left (-X)
];

export function cubeModelXml(options: CubeFixture = {}): string {
  const [sx, sy, sz] = options.size ?? [10, 10, 10];
  const vertices: [number, number, number][] = [
    [0, 0, 0], [sx, 0, 0], [sx, sy, 0], [0, sy, 0],
    [0, 0, sz], [sx, 0, sz], [sx, sy, sz], [0, sy, sz],
  ];

  const faces = CUBE_FACES.filter((_, index) => !(options.dropTop && index >= 2 && index <= 3));
  const triangles: [number, number, number][] = faces.map((face) =>
    options.flip ? [face[0], face[2], face[1]] : face
  );
  if (options.degenerate) triangles.push([0, 0, 1]);
  if (options.duplicate) triangles.push([...triangles[0]]);

  const vertexLines = vertices
    .map(([x, y, z]) => `   <vertex x="${x}" y="${y}" z="${z}"/>`)
    .join("\n");
  const triangleLines = triangles
    .map(([v1, v2, v3]) => `   <triangle v1="${v1}" v2="${v2}" v3="${v3}"/>`)
    .join("\n");

  const item = options.transform ? ` transform="${options.transform}"` : "";
  return `<?xml version="1.0" encoding="UTF-8"?>
<model unit="${options.unit ?? "millimeter"}" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">
 <metadata name="Application">Test Fixture</metadata>
 <resources>
  <object id="1" type="model" name="Cube">
   <mesh>
    <vertices>
${vertexLines}
    </vertices>
    <triangles>
${triangleLines}
    </triangles>
   </mesh>
  </object>
 </resources>
 <build>
  <item objectid="1"${item}/>
 </build>
</model>`;
}

function toBuffer(data: Uint8Array): ArrayBuffer {
  return data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength) as ArrayBuffer;
}

export function make3mf(entries: Record<string, string>): ArrayBuffer {
  const encoded: Record<string, Uint8Array> = {};
  for (const [name, content] of Object.entries(entries)) encoded[name] = strToU8(content);
  return toBuffer(zipSync(encoded, { level: 6 }));
}

/** 3MF puro com só o modelo — usado na maioria dos testes de malha. */
export function makeSimple3mf(options: CubeFixture = {}, extra: Record<string, string> = {}): ArrayBuffer {
  return make3mf({
    "[Content_Types].xml": CONTENT_TYPES,
    "_rels/.rels": RELS,
    [CORE_PATH]: cubeModelXml(options),
    "Metadata/thumbnail.png.b64": "iVBORw0KGgo=",
    ...extra,
  });
}

/** Projeto Bambu Studio fatiado com configuração propositalmente ruim (C1–C5). */
export function makeBambu3mf(): ArrayBuffer {
  const settings = JSON.stringify({
    nozzle_diameter: ["0.4"],
    layer_height: "0.4",
    wall_loops: "1",
    enable_support: "true",
    elephant_foot_compensation: "0",
    brim_type: "none",
    brim_width: "0",
    filament_colour: ["#FF0000"],
    printer_model: "A1",
  });

  return make3mf({
    "[Content_Types].xml": CONTENT_TYPES,
    "_rels/.rels": RELS,
    [CORE_PATH]: cubeModelXml({ size: [10, 10, 50] }),
    "Metadata/project_settings.config": settings,
    "Metadata/SliceInfo.config": "<slice_info></slice_info>",
    "Metadata/model_settings.config": "<model></model>",
    "Metadata/plate_1.gcode": "; GENERATED BY Bambu Studio\nM104 S0\n",
    "Metadata/thumbnail.png.b64": "iVBORw0KGgo=",
  });
}

